-- class_codes.trade -- the vocabulary the SCHEDULE already speaks
--
-- Owner, 2026-09-07: *"I also updated the class code mapping template list to properly
-- determine its trade that we have defined before in the schedule module."*
--
-- The template gained a "Trade" column (col 6, ahead of Description 1) and every one of its
-- 702 codes now carries one. This file lands that column on `class_codes`, so a BOQ line and a
-- schedule activity can finally be grouped by the SAME word.
--
-- WARNING WARNING THE TWO VOCABULARIES DO NOT MATCH YET, AND THE JOIN FAILS SILENTLY.
--   The schedule's canonical list is PRC_TRADE_ORDER in modules/project-schedule/index.html:
--     General Requirements, Site Works, Structural Works, Architectural Works, Mechanical Works,
--     Electrical and Auxiliary Works, Plumbing Works, Fire Protection Works, Allied Services,
--     Site Development Works
--   The template's seven are:
--     General Requirement, Site Works, Structural Works, Architectural Works, MEPF Works,
--     Allied Services Works, Others
--   Three differences, and each one produces ZERO matches with no error:
--     1. "General Requirement" vs "General Requirements"      -- 126 codes, singular/plural
--     2. "Allied Services Works" vs "Allied Services"         --   8 codes, suffix
--     3. "MEPF Works" (320 codes) has NO schedule counterpart -- the schedule splits it into
--        Mechanical / Electrical and Auxiliary / Plumbing / Fire Protection
--
--   WARNING THE VALUES ARE LOADED VERBATIM BELOW, NOT NORMALISED. Which spelling is
--   authoritative is a decision about Finance's chart and the schedule's trade list, not
--   something a migration should quietly pick -- and guessing wrong would move 454 of 702 codes
--   under a trade nobody chose. Section 3 holds the normalisation, COMMENTED OUT, for whichever
--   direction is decided.
--
-- Run in the Supabase SQL editor (Planners project). Idempotent / re-runnable.
-- ============================================================================

